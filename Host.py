class Host:
    def __init__(self, host_id, name, family_name,
                 email, password, id, address, phone_number):
        self.host_id = host_id
        self.name = name
        self.family_name = family_name
        self.email = email
        self.password = password
        self.id = id
        self.address = address
        self.phone_number = phone_number